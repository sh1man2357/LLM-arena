"""Generate the baseline's nine-cell line lookup; no runtime initialization cost."""
from pathlib import Path


def classify(code):
    cells = [(code // 3**i) % 3 for i in range(9)]
    if cells[4] != 1:
        return 0
    own = sum((c == 1) << i for i, c in enumerate(cells))
    blocked = sum((c == 2) << i for i, c in enumerate(cells))
    windows = [31 << i for i in range(5) if not (31 << i) & blocked]
    if any((own & w).bit_count() == 5 for w in windows):
        return 7
    def wins(mask):
        return {i for w in windows if (mask & w).bit_count() == 4
                for i in range(9) if w & (1 << i) and not (mask | blocked) & (1 << i)}
    winning = wins(own)
    if len(winning) >= 2:
        return 6
    if winning:
        return 5
    empty = [i for i in range(9) if not (own | blocked) & (1 << i)]
    if any(len(wins(own | (1 << i))) >= 2 for i in empty):
        return 4
    if any((own & w).bit_count() >= 3 for w in windows):
        return 3
    if sum((own & w).bit_count() >= 2 for w in windows) >= 2:
        return 2
    return int(any((own & w).bit_count() >= 2 for w in windows))


def generate():
    values = [classify(i) for i in range(3**9)]
    text = '// Generated by tools/build_gomoku_patterns.py.\n#pragma once\n#include <cstdint>\n'
    text += 'namespace champion { inline constexpr uint8_t patterns[19683] = {\n'
    text += '\n'.join(','.join(map(str, values[i:i+120])) + ',' for i in range(0, len(values), 120))
    return text + '\n}; }\n'


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1] / 'bots/gomoku/patterns.hpp').write_text(generate(), encoding='utf-8')
