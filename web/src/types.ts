export type Row = Record<string, any>;
export type Bot = { id: string; name: string; status: string; baseline: boolean; created: string;
  diagnostic?: string; compile_log?: { stderr?: string; stdout?: string } };
export type Player = { id: number; x: number; y: number; alive: boolean; death_tick: number | null };
export type Bomb = { id: number; owner_id: number; x: number; y: number; explode_at_tick: number; range: number };
export type World = { tick: number; grid: number[]; players: Player[]; bombs: Bomb[];
  fault_counters: { consecutive: number; total: number }[] };
export type Frame = { seq: number; tick: number | null; state: World; events: Row[];
  actions: {id: number; action: number}[]; calls: Row[];
  visual: {coverage: {x: number; y: number; owners: number[]}[]; exploded_bombs: Row[]; blocked_moves: number[]} };
export type Entrant = { id: string; name?: string; slot: number; wasm_sha256: string };
export type Replay = { frames: Frame[]; entrants: Entrant[]; rules: Row; initialization: Row[];
  width: number; height: number; result: Row | null; verified: boolean; partial: boolean;
  attempt_id: string; last_seq?: number; resync_required?: boolean };
export type Match = { id: string; title: string; status: string; entrants: Entrant[]; ticks: number;
  verified: boolean; result: Row | null; created: string; map_seed: number; diagnostic?: string };
export type Ranking = { id: string; name: string; rank: number; matches: number; wins: number;
  draws: number; losses: number; points: number; mean_score: number };
