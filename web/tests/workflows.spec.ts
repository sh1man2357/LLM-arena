import { test, expect } from '@playwright/test';

test('host collects and freezes source, compiles, watches live, runs and publishes a swapped batch', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const name = `浏览器 Wait ${Date.now()}`;
  const source = '#include "arena.hpp"\nnamespace bot { void init(uint64_t) {} Action tick(const GameState&) { return Action::WAIT; } }\n';
  await page.goto('/manage');
  await page.getByLabel('参赛者名称', { exact: true }).fill(name);
  await page.getByLabel('模型标识', { exact: true }).fill('工程检查，非模型生成');
  const receipt = page.waitForResponse(r => r.url().endsWith('/api/v1/sessions') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '记录收到任务，开始 60 分钟', exact: true }).click();
  const session = await (await receipt).json();
  await expect(page.getByLabel('选择收卷记录')).toHaveValue(session.id);
  await page.getByLabel('最终 bot.cpp', { exact: true }).fill(source);
  await page.getByRole('button', { name: '最终交卷并冻结', exact: true }).click();
  await expect(page.getByText('本次最终源码已冻结，可在提交记录中检查资格和诊断。')).toBeVisible();
  const submission = page.locator('.submission-row').filter({ hasText: name });
  const compileResponse = page.waitForResponse(r => r.url().endsWith('/compile') && r.request().method() === 'POST');
  await submission.getByRole('button', { name: '编译并检查资格', exact: true }).click();
  const compile = await (await compileResponse).json();
  await expect(submission.getByText('资格通过', { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(page.locator(`[data-job-id="${compile.id}"]`).getByText('已完成', { exact: true })).toBeVisible();
  await submission.getByText('编译日志与诊断', { exact: true }).click();
  await expect(submission.locator('.compile-log')).toContainText('exit_code');
  await page.getByRole('checkbox', { name: new RegExp(name) }).check();
  await page.getByRole('checkbox', { name: /^safe/ }).check();
  await page.getByLabel('比赛标题', { exact: true }).fill(`${name} 单局`);
  const matchResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/matches') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '启动双人单局', exact: true }).click();
  const matchJob = await (await matchResponse).json();
  await page.locator(`[data-job-id="${matchJob.id}"]`).getByRole('link', { name: '进入观赛' }).click();
  await expect(page.getByText('已确认的直播帧', { exact: true })).toBeVisible();
  await expect(page.locator('.versus-player').filter({ hasText: name })).toBeVisible();
  await page.getByRole('button', { name: '初始帧 (Home)', exact: true }).click();
  await expect(page.getByRole('slider', { name: '回放帧' })).toHaveValue('0');
  await page.getByLabel('播放速度').selectOption('0.25');
  await expect(page.getByRole('button', { name: '回到最新', exact: true })).toBeVisible();
  await expect(page.getByText('世界回放已验证', { exact: true })).toBeVisible({ timeout: 40000 });
  await expect(page.getByRole('slider', { name: '回放帧' })).toHaveValue('0');
  await page.getByRole('button', { name: '最后已接收帧 (End)', exact: true }).click();
  await expect(page.getByText('双方平局', { exact: true })).toBeVisible();
  await page.goto('/manage');
  await page.getByRole('checkbox', { name: new RegExp(name) }).check();
  await page.getByRole('checkbox', { name: /^safe/ }).check();
  await page.getByLabel('比赛标题', { exact: true }).fill(`${name} 隐藏批次`);
  await page.getByLabel('批次地图数', { exact: true }).fill('1');
  await page.getByRole('checkbox', { name: '正式隐藏批次，收卷关闭前封存地图', exact: true }).check();
  const batchResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/tournaments') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '创建全配对批次', exact: true }).click();
  const batchJob = await (await batchResponse).json();
  const batch = page.locator('.publication-row').filter({ hasText: `${name} 隐藏批次` });
  await batch.getByRole('button', { name: '关闭收卷并开放观看', exact: true }).click();
  await expect(page.locator(`[data-job-id="${batchJob.id}"]`).getByText('已完成', { exact: true })).toBeVisible({ timeout: 20000 });
  await batch.getByRole('button', { name: '校验并发布成绩', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '成绩发布记录已保存' })).toBeVisible();
  await batch.getByRole('link').click();
  await expect(page.locator('.ranking-row')).toHaveCount(2);
  await expect(page.locator('.match-row')).toHaveCount(2);
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: '导出报告' }).click();
  expect((await download).suggestedFilename()).toContain('-report.json');
  expect(errors).toEqual([]);
});

test('invalid C++ stays frozen with a readable qualification failure', async ({ page }) => {
  const name = `故障源码 ${Date.now()}`;
  await page.goto('/manage');
  await page.getByLabel('参赛者名称', { exact: true }).fill(name);
  await page.getByRole('button', { name: '记录收到任务，开始 60 分钟', exact: true }).click();
  await expect(page.getByLabel('最终 bot.cpp')).toBeVisible();
  await page.getByLabel('最终 bot.cpp').fill('this is invalid C++');
  await page.getByRole('button', { name: '最终交卷并冻结', exact: true }).click();
  const record = page.locator('.submission-row').filter({ hasText: name });
  await record.getByRole('button', { name: '编译并检查资格', exact: true }).click();
  await expect(record.getByText('资格失败', { exact: true })).toBeVisible({ timeout: 15000 });
  await record.getByText('编译日志与诊断', { exact: true }).click();
  await expect(record.locator('.compile-log')).toContainText('error:');
  await expect(page.getByLabel('最终 bot.cpp')).toHaveCount(0);
  await expect(page.getByRole('checkbox', { name: new RegExp(name) })).toHaveCount(0);
});
