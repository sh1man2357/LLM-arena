import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

test('public Replay roundtrip and complete private backup download use real current data', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const original = await page.request.get('/api/v1/exports/reference-chain');
  expect(original.ok()).toBeTruthy();
  const exported = await original.body();
  await page.goto('/manage');
  const receipt = page.waitForResponse(r => r.url().endsWith('/api/v1/imports/replay') && r.request().method() === 'POST');
  await page.getByLabel('上传 Replay', { exact: true }).setInputFiles({ name: 'chain-public.json', mimeType: 'application/json', buffer: exported });
  const imported = await (await receipt).json();
  expect(imported.source_format).toBe('public_projection');
  await page.goto(`/matches/${imported.id}?frame=19`);
  await expect(page.getByText('世界回放已验证', { exact: true })).toBeVisible();
  await expect(page.getByText(/公开副本：已重算世界轨迹/)).toBeVisible();
  await expect(page.getByRole('slider', { name: '回放帧' })).toHaveValue('19');
  await expect(page.getByText('淘汰于 Tick 18')).toHaveCount(2);
  await expect(page.getByText('双方平局', { exact: true })).toBeVisible();
  await page.goto('/manage');
  const backupResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/backups') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '创建完整私有备份', exact: true }).click();
  const job = await (await backupResponse).json();
  await expect.poll(async () => (await (await page.request.get(`/api/v1/jobs/${job.id}`)).json()).status,
    { timeout: 10000 }).toBe('running');
  expect((await page.request.get('/health')).status()).toBe(200);
  expect((await page.request.get(`/api/v1/matches/${imported.id}/frames`)).status()).toBe(200);
  expect((await page.request.post('/api/v1/sessions', { data: { name: '备份期间不会创建此记录' } })).status()).toBe(423);
  await expect(page.locator(`[data-job-id="${job.id}"] .job-info > .record-heading`).getByText('已完成', { exact: true })).toBeVisible({ timeout: 90000 });
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载私有备份', exact: true }).first().click();
  const download = await downloadEvent;
  const row = (await (await page.request.get('/api/v1/backups')).json()).items[0];
  const output = resolve('../artifacts/work/v0.2-recovery-browser-download'); mkdirSync(output, { recursive: true });
  const downloadedPath = resolve(output, `private-backup-${row.id}.zip`);
  await download.saveAs(downloadedPath);
  const bytes = readFileSync(downloadedPath);
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(row.sha256);
  expect(row.contains_private_inputs).toBeTruthy();
  expect(row.files).toBeGreaterThan(500);
  const publicViewer = await page.context().browser()!.newContext();
  expect((await publicViewer.request.get(new URL(`/api/v1/backups/${row.id}`, page.url()).href)).status()).toBe(403);
  await publicViewer.close();
  expect(errors).toEqual([]);
});
